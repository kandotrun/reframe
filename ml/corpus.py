def build_dataset() -> list[dict]:
    """Return deterministic labeled candidate lists, with disjoint text pools.

    Positive documents include old/new discussions where present. Relevance
    labels do not encode which revision is active or whether an action is safe.
    """
    by_key = {theme["key"]: theme for theme in THEMES}
    rows: list[dict] = []
    for split in ("train", "dev", "test"):
        for theme in THEMES:
            family = f"{theme['key']}_{split}_scenario"
            situation = theme[split]
            for query_index, query in enumerate(situation["queries"]):
                example_id = f"{family}_q{query_index + 1:02d}"
                seed = int.from_bytes(
                    hashlib.sha256(example_id.encode()).digest()[:8], "big"
                )
                rng = random.Random(seed)
                # 3 target + 9 neighboring-theme + 6 other-theme documents.
                selected = [(theme, index) for index in range(3)]
                for neighbor in theme["neighbors"]:
                    selected.extend((by_key[neighbor], index) for index in range(3))
                other_keys = [
                    key
                    for key in by_key
                    if key != theme["key"] and key not in theme["neighbors"]
                ]
                rng.shuffle(other_keys)
                selected.extend(
                    (by_key[key], rng.randrange(3)) for key in other_keys[:6]
                )
                candidates = []
                for candidate_theme, doc_index in selected:
                    is_target = candidate_theme["key"] == theme["key"]
                    relevance = (2 if doc_index < 2 else 1) if is_target else 0
                    reason = (
                        "問い合わせの対象となる業務と確認事項を直接説明する。"
                        if relevance == 2
                        else (
                            "同じ業務の判断を補助する記録や実績を説明する。"
                            if relevance == 1
                            else "共有語があっても、この問い合わせとは確認対象の業務が異なる。"
                        )
                    )
                    candidates.append(
                        {
                            "id": f"{candidate_theme['key']}_{split}_d{doc_index+1}",
                            "text": candidate_theme[split]["docs"][doc_index],
                            "relevance": relevance,
                            "reason": reason,
                        }
                    )
                rng.shuffle(candidates)
                rows.append(
                    {
                        "id": example_id,
                        "family": family,
                        "split": split,
                        "query": query,
                        "candidates": candidates,
                        "scenario": situation["scenario"],
                    }
                )
    return rows


def dataset_summary() -> dict:
    rows = build_dataset()
    documents: dict[str, str] = {}
    for row in rows:
        for candidate in row["candidates"]:
            documents[candidate["id"]] = candidate["text"]
    return {
        "queries": len(rows),
        "splits": dict(Counter(row["split"] for row in rows)),
        "families": len({row["family"] for row in rows}),
        "documents": len(documents),
        "candidate_pairs": sum(len(row["candidates"]) for row in rows),
        "label_counts": dict(
            Counter(
                candidate["relevance"]
                for row in rows
                for candidate in row["candidates"]
            )
        ),
    }


if __name__ == "__main__":
    import json

    print(json.dumps(dataset_summary(), ensure_ascii=False, indent=2))
